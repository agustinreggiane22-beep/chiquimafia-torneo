// Run after editing any source stylesheet. Output stays in css/ to preserve URL paths.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..');
const sources=["fonts.css", "styles.css", "enhancements.css", "corrections.css", "home.css", "theme.css", "hall-of-fame.css", "live-score.css", "mvp-voting.css", "sports-panels.css", "page-background.css", "duels.css", "team-levels.css", "assists.css", "player-experience.css"];
function build(){return '/* Generated by node scripts/build-styles.cjs. Edit the source stylesheets, then rebuild. */\n'+sources.map(file=>`/* ${file} */\n${fs.readFileSync(path.join(root,'css',file),'utf8')}`).join('\n').trimEnd()+'\n'}
if(require.main===module){
 const css=build(),filename='site-'+crypto.createHash('sha256').update(css).digest('hex').slice(0,12)+'.css',folder=path.join(root,'css');
 // Keep the stable bundle for secondary pages and use a content-specific URL on home.
 fs.writeFileSync(path.join(folder,'site.css'),css);
 fs.writeFileSync(path.join(folder,filename),css);
 const index=path.join(root,'index.html'),html=fs.readFileSync(index,'utf8');
 if(!/href="css\/site(?:-[a-f0-9]{12})?\.css(?:\?[^"]*)?"/.test(html))throw new Error('Home stylesheet link not found');
 fs.writeFileSync(index,html.replace(/href="css\/site(?:-[a-f0-9]{12})?\.css(?:\?[^"]*)?"/,'href="css/'+filename+'"'));
 for(const file of fs.readdirSync(folder))if(/^site-[a-f0-9]{12}\.css$/.test(file)&&file!==filename)fs.unlinkSync(path.join(folder,file));
 console.log('Built css/'+filename+' from '+sources.length+' source stylesheets; updated index.html.');
}
module.exports={build,sources};
